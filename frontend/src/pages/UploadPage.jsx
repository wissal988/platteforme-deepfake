function getMediaType(file) {
  if (file.type.startsWith("video")) return "VIDEO"
  if (file.type.startsWith("image")) return "IMAGE"
  if (file.type.startsWith("audio")) return "AUDIO"
  return null
}

function MediaIcon({ type, size = 16 }) {
  const cls = `text-slate-500 dark:text-slate-400`
  if (type === "VIDEO") return <FileVideo size={size} className={cls} />
  if (type === "IMAGE") return <FileImage size={size} className={cls} />
  return <FileAudio size={size} className={cls} />
}

function Badge({ label }) {
  const styles = {
    FAKE: "bg-red-50 text-red-700 dark:bg-red-950/40 dark:text-red-300",
    REAL: "bg-emerald-50 text-emerald-700 dark:bg-emerald-950/40 dark:text-emerald-300",
    "NON-COMPLIANT": "bg-red-50 text-red-700 dark:bg-red-950/40 dark:text-red-300",
    COMPLIANT: "bg-emerald-50 text-emerald-700 dark:bg-emerald-950/40 dark:text-emerald-300",
    IMAGE: "bg-blue-50 text-blue-700 dark:bg-blue-950/40 dark:text-blue-300",
    VIDEO: "bg-red-50 text-red-700 dark:bg-red-950/40 dark:text-red-300",
    AUDIO: "bg-emerald-50 text-emerald-700 dark:bg-emerald-950/40 dark:text-emerald-300",
  }
  return (
    <span className={`inline-flex px-2 py-0.5 rounded-md text-xs font-medium ${styles[label] || "bg-slate-100 text-slate-600"}`}>
      {label}
    </span>
  )
}

