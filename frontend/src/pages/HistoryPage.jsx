function Badge({ label, type }) {
  const styles = {
    FAKE: "bg-red-50 text-red-700 dark:bg-red-950/40 dark:text-red-300",
    REAL: "bg-emerald-50 text-emerald-700 dark:bg-emerald-950/40 dark:text-emerald-300",
    IMAGE: "bg-blue-50 text-blue-700 dark:bg-blue-950/40 dark:text-blue-300",
    VIDEO: "bg-violet-50 text-violet-700 dark:bg-violet-950/40 dark:text-violet-300",
    AUDIO: "bg-emerald-50 text-emerald-700 dark:bg-emerald-950/40 dark:text-emerald-300",
  }
  return (
    <span className={`inline-flex px-2 py-0.5 rounded-md text-xs font-medium ${styles[type || label] || "bg-slate-100 text-slate-600"}`}>
      {label}
    </span>
  )
}

function TypeIcon({ type }) {
  const cls = "w-3.5 h-3.5 text-slate-400 dark:text-slate-500"
  if (type === "VIDEO") return <FileVideo className={cls} />
  if (type === "IMAGE") return <FileImage className={cls} />
  return <FileAudio className={cls} />
}

