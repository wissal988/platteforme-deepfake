export default function HistoryPage() {
  const { t, i18n } = useTranslation()
  const [history, setHistory] = useState([])
  const [loading, setLoading] = useState(true)
  const [activeFilter, setActiveFilter] = useState("all")
  const [reportLang, setReportLang] = useState("fr")

  useEffect(() => {
    api.get("/analysis/history")
      .then((res) => setHistory(Array.isArray(res.data) ? res.data : []))
      .catch(() => setHistory([]))
      .finally(() => setLoading(false))
  }, [])

  // Charger le logo en base64 pour l'inclure dans le PDF
  const [logoBase64, setLogoBase64] = useState("")
  useEffect(() => {
    fetch("/src/assets/entv-logo.png")
      .then(r => r.blob())
      .then(blob => {
        const reader = new FileReader()
        reader.onload = () => setLogoBase64(reader.result)
        reader.readAsDataURL(blob)
      })
      .catch(() => setLogoBase64(""))
  }, [])

  const filters = [
    { key: "all", label: t("filterAll") },
    { key: "FAKE", label: t("filterFake") },
    { key: "REAL", label: t("filterReal") },
    { key: "IMAGE", label: t("filterImages") },
    { key: "VIDEO", label: t("filterVideos") },
    { key: "AUDIO", label: t("filterAudios") },
  ]

  const filtered = history.filter((h) => {
    if (activeFilter === "all") return true
    if (["FAKE", "REAL"].includes(activeFilter)) return h.label === activeFilter
    return h.media_type === activeFilter
  })

  return (
    <div className="max-w-6xl mx-auto">
      <div className="mb-5">
        <h1 className="text-xl font-medium">{t("historyTitle")}</h1>
        <p className="text-sm text-slate-500 dark:text-slate-400 mt-0.5">{t("historySub")}</p>
      </div>

      {/* Filters + langue rapport */}
      <div className="flex flex-wrap gap-2 mb-4 items-center justify-between">
        <div className="flex gap-2 flex-wrap">
          {filters.map(({ key, label }) => (
            <button
              key={key}
              onClick={() => setActiveFilter(key)}
              className={`px-3.5 py-1.5 rounded-xl text-sm transition ${
                activeFilter === key
                  ? "bg-red-50 dark:bg-red-950/40 text-red-700 dark:text-red-300 border border-red-200 dark:border-red-800"
                  : "border border-slate-200 dark:border-slate-700 text-slate-600 dark:text-slate-400 hover:bg-slate-50 dark:hover:bg-slate-800"
              }`}
            >
              {label}
            </button>
          ))}
        </div>
        <div className="flex items-center gap-2">
          <span className="text-xs text-slate-500">Langue rapport :</span>
          {["fr", "en", "ar"].map((l) => (
            <button
              key={l}
              onClick={() => setReportLang(l)}
              className={`px-3 py-1 rounded-lg text-xs font-medium transition border ${
                reportLang === l
                  ? "bg-green-700 text-white border-green-700"
                  : "border-slate-300 dark:border-slate-600 text-slate-600 dark:text-slate-400 hover:bg-slate-50 dark:hover:bg-slate-800"
              }`}
            >
              {l.toUpperCase()}
            </button>
          ))}
        </div>
      </div>

      {/* Table */}
      <div className="bg-white dark:bg-slate-900 rounded-2xl border border-slate-200 dark:border-slate-800 overflow-hidden">
        <div className="grid grid-cols-[2fr_1fr_1.2fr_1fr_1fr_auto] text-xs font-medium text-slate-400 dark:text-slate-500 px-4 py-3 border-b border-slate-100 dark:border-slate-800 bg-slate-50 dark:bg-slate-800/50 uppercase tracking-wide">
          <div>{t("colFile")}</div>
          <div>{t("colType")}</div>
          <div>{t("colDate")}</div>
          <div>{t("colResult")}</div>
          <div>{t("colScore")}</div>
          <div>Rapport</div>
        </div>

        {loading ? (
          <div className="flex items-center justify-center py-16">
            <div className="w-6 h-6 border-2 border-red-500 border-t-transparent rounded-full animate-spin" />
          </div>
        ) : filtered.length === 0 ? (
          <div className="py-16 text-center text-sm text-slate-400 dark:text-slate-500">
            {t("noHistory")}
          </div>
        ) : (
          filtered.map((item, i) => (
            <div
              key={i}
              className="grid grid-cols-[2fr_1fr_1.2fr_1fr_1fr_auto] px-4 py-3.5 border-b border-slate-100 dark:border-slate-800 last:border-0 items-center hover:bg-slate-50 dark:hover:bg-slate-800/50 transition"
            >
              <div className="flex items-center gap-2 min-w-0">
                <div className="w-7 h-7 rounded-lg bg-slate-100 dark:bg-slate-800 flex items-center justify-center flex-shrink-0">
                  <TypeIcon type={item.media_type} />
                </div>
                <span className="text-sm truncate">{item.original_name || item.media_file_id || "—"}</span>
              </div>
              <div><Badge label={item.media_type || "?"} type={item.media_type} /></div>
              <div className="text-sm text-slate-500 dark:text-slate-400">
                {item.created_at ? new Date(item.created_at).toLocaleString() : "—"}
              </div>
              <div><Badge label={item.label || "?"} type={item.label} /></div>
              <div className="text-sm text-slate-600 dark:text-slate-300 font-mono">
                {item.score ? parseFloat(item.score).toFixed(4) : "—"}
              </div>
              <div>
                <button
                  onClick={() => openReport(item, reportLang, logoBase64)}
                  className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg bg-red-600 hover:bg-red-700 text-white text-xs font-medium transition"
                >
                  <FileText size={11} />
                  PDF
                </button>
              </div>
            </div>
          ))
        )}
      </div>
    </div>
  )
}